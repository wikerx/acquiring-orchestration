  `client_ip_country` CHAR(3) NULL COMMENT '客户端 IP 国家或地区。',
  `user_agent_hash` CHAR(64) NULL COMMENT 'User-Agent 摘要。',
  `device_id_hash` CHAR(64) NULL COMMENT '设备 ID 摘要。',
