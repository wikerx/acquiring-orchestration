-- Hosted Checkout V1 dev/test DDL
-- 说明：
-- 1. 本脚本仅用于 dev/test 环境建表和变更评审，生产执行前必须走正式数据库变更流程。
-- 2. 收银台表只保存会话、URL token、支付尝试、页面事件和安全事件，不保存 PAN、CVV、JWT、CAVV 明文。
-- 3. opaqueToken 和 3DS return token 均只保存 HMAC-SHA256 摘要。

SET NAMES utf8mb4;

