  `token_hash` CHAR(64) NOT NULL COMMENT 'opaqueToken HMAC-SHA256 摘要。',
  `token_hash_alg` VARCHAR(32) NOT NULL DEFAULT 'HMAC_SHA256' COMMENT 'token 摘要算法。',
  `token_key_version` VARCHAR(32) NOT NULL COMMENT 'token pepper/key 版本。',
  `token_status` VARCHAR(32) NOT NULL COMMENT 'token 状态，如 ACTIVE、REVOKED、EXPIRED。',
  `issue_reason` VARCHAR(64) NULL COMMENT '签发原因，如 CREATE、REISSUE。',
  `expire_time` DATETIME(3) NOT NULL COMMENT 'token 过期时间。',
  `first_used_time` DATETIME(3) NULL COMMENT '首次使用时间。',
  `last_used_time` DATETIME(3) NULL COMMENT '最近一次使用时间。',
  `use_count` INT NOT NULL DEFAULT 0 COMMENT '使用次数。',
  `last_client_ip_hash` CHAR(64) NULL COMMENT '最近一次使用客户端 IP 摘要。',
  `last_user_agent_hash` CHAR(64) NULL COMMENT '最近一次使用 User-Agent 摘要。',
  `revoked_time` DATETIME(3) NULL COMMENT '吊销时间。',
  `revoke_reason_code` VARCHAR(64) NULL COMMENT '吊销原因码。',
  `version` INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本号。',
  `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '软删除标识，0未删除，1已删除。',
  `create_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间。',
  `update_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间。',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_checkout_token_id` (`checkout_token_id`),
  UNIQUE KEY `uk_token_hash` (`token_hash`),
  KEY `idx_session_status` (`checkout_session_id`, `token_status`),
  KEY `idx_merchant_expire` (`merchant_id`, `expire_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='Hosted Checkout URL token 摘要表。';

