  `allowed_payment_methods_json` JSON NOT NULL COMMENT '商户允许的支付方式快照。',
  `selected_payment_method` VARCHAR(32) NULL COMMENT '最近一次选择的支付方式。',
  `selected_payment_brand` VARCHAR(32) NULL COMMENT '最近一次选择的支付品牌。',
  `channel_code` VARCHAR(32) NULL COMMENT '最近一次使用的渠道编码。',
  `channel_mid_config_id` BIGINT NULL COMMENT '最近一次使用的渠道 MID 配置 ID。',
  `merchant_display_name` VARCHAR(256) NULL COMMENT '商户主体展示名称。',
  `merchant_logo_url` VARCHAR(512) NULL COMMENT '商户 Logo URL。',
  `merchant_return_url` VARCHAR(512) NULL COMMENT '付款完成后返回商户页面的 URL。',
  `merchant_cancel_url` VARCHAR(512) NULL COMMENT '付款人取消时返回商户页面的 URL。',
  `merchant_notify_url_hash` CHAR(64) NULL COMMENT '商户通知地址 SHA-256 摘要。',
  `locale` VARCHAR(16) NULL COMMENT '默认页面语言。',
  `payer_country` CHAR(3) NULL COMMENT '付款人国家或地区，ISO 3166-1 alpha-3。',
  `payer_email_masked` VARCHAR(256) NULL COMMENT '付款人邮箱脱敏值。',
  `payer_email_hash` CHAR(64) NULL COMMENT '付款人邮箱 SHA-256 摘要。',
  `retry_allowed` TINYINT NOT NULL DEFAULT 1 COMMENT '是否允许付款失败后重试，0否，1是。',
  `max_attempt_count` INT NOT NULL DEFAULT 3 COMMENT '最大付款尝试次数。',
  `attempt_count` INT NOT NULL DEFAULT 0 COMMENT '已创建付款尝试次数。',
  `success_attempt_id` VARCHAR(64) NULL COMMENT '成功付款尝试号。',
  `last_attempt_id` VARCHAR(64) NULL COMMENT '最近一次付款尝试号。',
  `checkout_domain` VARCHAR(256) NOT NULL COMMENT '收银台页面域名。',
  `expire_time` DATETIME(3) NOT NULL COMMENT '会话过期时间。',
  `paid_time` DATETIME(3) NULL COMMENT '支付成功时间。',
  `cancel_time` DATETIME(3) NULL COMMENT '取消时间。',
  `blocked_time` DATETIME(3) NULL COMMENT '安全拦截时间。',
  `block_reason_code` VARCHAR(64) NULL COMMENT '安全拦截原因码。',
  `last_open_time` DATETIME(3) NULL COMMENT '最近一次打开页面时间。',
