  KEY `idx_operation` (`operation_id`, `transaction_date_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='Hosted Checkout 会话主表。';

CREATE TABLE IF NOT EXISTS `payment_checkout_token` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理主键。',
